#!/usr/bin/env node
// Writes THIRD-PARTY-NOTICES.md: the full licence text of everything the build bundles into index.html.
//   node scripts/notices.mjs            write the file
//   node scripts/notices.mjs --check    exit 1 if the file on disk is out of date
// The built page itself carries a short notice for each (scripts/build.mjs); this is the long form.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = p => fs.readFileSync(path.join(ROOT, "node_modules", p), "utf8").replace(/\r\n/g, "\n").trim();
const version = p => p + " " + JSON.parse(read(p + "/package.json")).version;

const PARTS = [
  { name: "React and React DOM", version: version("react") + ", " + version("react-dom"), licence: "MIT", used: "the interface", text: read("react/LICENSE") },
  { name: "Inter", version: version("@fontsource-variable/inter"), licence: "SIL Open Font License 1.1", used: "the interface typeface (bundled as “TST Sans”, a subset)", text: read("@fontsource-variable/inter/LICENSE") },
  { name: "JetBrains Mono", version: version("@expo-google-fonts/jetbrains-mono"), licence: "SIL Open Font License 1.1", used: "the monospace typeface for the log, the numbers and the CRT (bundled as “TST Mono”, a subset)", text: read("@expo-google-fonts/jetbrains-mono/LICENSE_FONT") },
  { name: "Lucide", version: version("lucide-static"), licence: "ISC", used: "the icons", text: read("lucide-static/LICENSE") }
];

const fence = "```";
const out = [
  "# Third-party notices",
  "",
  "`index.html` is one self-contained file. It bundles the following works, each under its own licence. The game's own code and writing are not covered by these notices.",
  "",
  "| Work | Package | Licence | Used for |",
  "|---|---|---|---|",
  ...PARTS.map(p => `| ${p.name} | ${p.version} | ${p.licence} | ${p.used} |`),
  "",
  "The two typefaces are subset to the characters the game uses and bundled under different family names, as the Open Font License asks of modified versions.",
  "",
  ...PARTS.flatMap(p => [`## ${p.name}`, "", fence, p.text, fence, ""]),
  "_This file is generated by `node scripts/notices.mjs` from the packages in `node_modules`._",
  ""
].join("\n");

const file = path.join(ROOT, "THIRD-PARTY-NOTICES.md");
if (process.argv.includes("--check")) {
  const have = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (have !== out) { console.error("THIRD-PARTY-NOTICES.md is out of date: run node scripts/notices.mjs"); process.exit(1); }
  console.log("THIRD-PARTY-NOTICES.md is up to date");
} else {
  fs.writeFileSync(file, out);
  console.log("THIRD-PARTY-NOTICES.md  " + PARTS.length + " works, " + Math.round(out.length / 1024) + " KB");
}
